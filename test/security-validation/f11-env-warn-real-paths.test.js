// F11 (MEDIUM, FIXED): found on a real Mac, not by unit tests. The shipped
// default policy warned on `.env` and `.env.*`, which glob-match treats as
// EXACT relative names: they matched only the bare string ".env". Real tool
// calls use ./.env, absolute paths (the MCP filesystem server requires them),
// Windows paths, and variants like .env.local - none of which warned, so the
// default "sensitive file" protection never fired for the most common tool.
// The engine was right (see glob-match.test.js); the policy DATA was wrong.
// These tests load the SHIPPED policy files so the data cannot regress.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import yaml from 'js-yaml';
import { fileURLToPath } from 'node:url';

import { PolicyEngine, applyDefaults } from '../../src/core/policy-engine.js';
import { createAction } from '../../src/core/action.js';
import { ensurePolicy } from '../../src/adapters/wrap/policy-file.js';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const ctx = { source: 'mcp', sessionId: 's1' };

const shouldWarn = [
  '.env',
  './.env',
  '/Users/someone/project/.env',
  '/home/someone/project/sub/dir/.env',
  'C:\\Users\\someone\\project\\.env',
  '/Users/someone/project/.env.local',
  '/Users/someone/project/.env.production',
  'config/.env.staging',
];
const shouldNotWarn = ['/Users/someone/project/.environment', 'notenv', '/Users/someone/project/env', '/Users/someone/project/my.env.txt'];

function verdicts(engine, values) {
  return values.map((v) => [v, engine.evaluate(createAction({ verb: 'read', resourceType: 'filesystem', resourceValue: v, context: ctx })).verdict]);
}

function check(label, engine) {
  for (const [value, verdict] of verdicts(engine, shouldWarn)) assert.equal(verdict, 'WARN', `${label}: ${value} should WARN`);
  for (const [value, verdict] of verdicts(engine, shouldNotWarn)) assert.equal(verdict, 'ALLOW', `${label}: ${value} should NOT warn`);
}

const load = (rel) => new PolicyEngine(applyDefaults(yaml.load(fs.readFileSync(path.join(root, rel), 'utf8'))));

test('F11: the shipped default policy warns on .env files however the path is written', () => {
  check('policy/default-policy.yaml', load('policy/default-policy.yaml'));
});

test('F11: the demo policy warns the same way', () => {
  check('examples/demo-policy.yaml', load('examples/demo-policy.yaml'));
});

test('F11: a policy GENERATED by `agentguard wrap` (a copy of the default) warns the same way', () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'ag-f11-'));
  try {
    const policyPath = path.join(dir, 'policy.yaml');
    ensurePolicy({ policyPath, names: ['s'], backupDir: path.join(dir, 'bk') });
    check('generated policy', new PolicyEngine(applyDefaults(yaml.load(fs.readFileSync(policyPath, 'utf8')))));
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
});
